#!/usr/bin/env python3
"""Generate address-only JIT watch tables from a layout, without reading a ROM.

Unlike recomp.py this emits no game instructions or code images. The interpreter
and JIT execute the player's ROM; the tables only identify active game screens.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys


def generate(layout_path, out):
    layout = json.loads(Path(layout_path).read_text())
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    alternatives = [json.loads(p.read_text()) for p in Path(__file__).parent.glob('*.json')]
    probes = {}
    for name, sec, execute, init, init_sec, exit_, exit_sec in layout['apps']:
        for section, address in [(sec, execute), (init_sec, init), (exit_sec, exit_)]:
            if address:
                probes.setdefault(section, set()).add(address)
    for _, section, address in layout['focus']:
        probes.setdefault(section, set()).add(address)
    rows = []
    sections = []
    ranges = []
    for index, section in enumerate(layout['sections']):
        first = len(rows)
        code = section['ranges']
        named = sorted(set(section['named']) | probes.get(section['name'], set()))
        for start, end, thumb in code:
            cuts = [start] + [a for a in named if start < a < end] + [end]
            for a, b in zip(cuts, cuts[1:]):
                rows.append(f'    {{0x{a:08X}u, 0x{b:08X}u, {thumb}, {index}, nullptr}},')
        values = ', '.join(f'{{0x{a:08X}u, 0x{b:08X}u}}' for a, b, _ in code)
        ranges.append(f'static const RcRange ranges_{index}[] = {{{values}}};')
        base = min([section['base']] + [a.get('overlay_bases', {}).get(section['name'], section['base']) for a in alternatives])
        size = section['size'] + section['base'] - base
        sections.append(f'    {{"{section["name"]}", 0x{base:08X}u, 0x{size:X}u, nullptr, ranges_{index}, {len(code)}, {first}, {len(rows)-first}}},')
    text = ['// Address metadata only; no game code. Generated by layout_tables.py.',
            '#include "recomp_rt.h"', *ranges, 'const RcChunk rc_chunks[] = {',
            *rows, '};', f'const melonDS::u32 rc_num_chunks = {len(rows)};',
            'RcSection rc_sections[] = {', *sections, '};',
            f'const melonDS::u32 rc_num_sections = {len(sections)};', '']
    (out / 'rc_tables.cpp').write_text('\n'.join(text), newline='\n')
    subprocess.run([sys.executable, str(Path(__file__).parents[1] / 'apps.py'),
                    '--layout', str(layout_path), str(out)], check=True)
    print(f'{len(rows)} address-only chunks, {len(sections)} sections; no ROM required')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('layout')
    parser.add_argument('out')
    args = parser.parse_args()
    generate(args.layout, args.out)
